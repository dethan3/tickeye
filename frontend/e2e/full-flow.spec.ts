import { expect, test } from '@playwright/test'

test('completes the local risk-control flow without mutating positions from a Scenario', async ({ page }) => {
  await page.goto('/portfolio')
  await expect(page.getByRole('heading', { name: '我的持仓' })).toBeVisible()

  await page.getByLabel('账户名称').fill('长期账户')
  await page.getByLabel('标的代码').fill('510300')
  await page.getByLabel('标的名称').fill('沪深300ETF')
  await page.getByLabel('标的类型').selectOption('etf')
  await page.getByLabel('资产类别').selectOption('equity')
  await page.getByLabel('数量').fill('10')
  await page.getByLabel('手工市值（元）').fill('999')
  await page.getByRole('button', { name: '保存并创建快照' }).click()
  await expect(page.locator('.position-table')).toContainText('沪深300ETF')

  await page.getByLabel('账户名称').fill('现金账户')
  await page.getByLabel('标的代码').fill('CASH-CNY')
  await page.getByLabel('标的名称').fill('人民币现金')
  await page.getByLabel('标的类型').selectOption('cash')
  await page.getByLabel('资产类别').selectOption('cash')
  await page.getByLabel('手工市值（元）').fill('1000')
  await page.getByRole('button', { name: '保存并创建快照' }).click()
  await expect(page.locator('.position-table')).toContainText('人民币现金')

  await page.getByRole('link', { name: '观察' }).click()
  await page.getByLabel('新分组').fill('待比较')
  await page.getByRole('button', { name: '创建' }).click()
  await expect(page.getByRole('heading', { name: '待比较' })).toBeVisible()
  await page.getByLabel('代码').fill('159915')
  await page.getByLabel('名称').fill('创业板ETF')
  await page.getByLabel('类型').selectOption('etf')
  await page.getByLabel('观察理由').fill('用于比较降低单一标的依赖的可能性')
  await page.getByLabel('标签').fill('候选，成长')
  await page.getByRole('button', { name: '加入当前分组' }).click()
  await expect(page.locator('.watch-item')).toContainText('创业板ETF')
  await expect(page.locator('.watch-item')).toContainText('缺少行情')

  await page.getByRole('link', { name: '数据质量' }).click()
  await page.getByRole('button', { name: '刷新全部行情' }).click()
  await expect(page.getByRole('status')).toContainText('2 个成功')
  await expect(page.getByText('行情可用')).toHaveCount(0)
  await expect(page.getByText('可用')).toHaveCount(2)

  await page.getByRole('link', { name: '概览' }).click()
  await page.getByRole('button', { name: '生成第一份风险快照' }).click()
  await expect(page.getByText('历史风险可计算')).toBeVisible()
  await expect(page.getByText('历史风险已有数据，但尚无个人边界结论')).toBeVisible()
  await expect(page.getByRole('link', { name: '按需设置风险边界' })).toBeVisible()

  await page.getByRole('link', { name: '规则' }).click()
  await page.getByLabel('规则类型').selectOption('cash_min_weight')
  await page.getByLabel('边界（%）').fill('10')
  await page.getByLabel('关注缓冲（%）').fill('20')
  await page.getByRole('button', { name: '保存规则并重新评估' }).click()
  await expect(page.locator('.policy-rule-list article').getByText('现金最低比例')).toBeVisible()

  await page.getByRole('link', { name: '观察' }).click()
  await page.getByRole('button', { name: '模拟调整风险' }).click()
  await expect(page.getByRole('heading', { name: '创业板ETF 风险调整模拟' })).toBeVisible()
  await page.getByLabel('操作').selectOption('buy')
  await page.getByLabel('标的').selectOption({ label: '创业板ETF (159915)' })
  await page.getByLabel('金额（元）').fill('100')
  await page.getByLabel('估计交易成本（元）').fill('1')
  await page.getByRole('button', { name: '应用调整并比较风险' }).click()
  await expect(page.getByText('模拟调整 / 调整后')).toBeVisible()
  await expect(page.getByText('总估计成本 ¥100.00')).toHaveCount(0)
  await expect(page.getByText(/总估计成本/)).toContainText('¥1.00')

  await page.getByRole('link', { name: '持仓' }).click()
  await expect(page.locator('.position-table')).not.toContainText('创业板ETF')
  await expect(page.locator('.position-table')).toContainText('沪深300ETF')
})
